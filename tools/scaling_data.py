"""Points for E-01's scatter (Fig. 06): training power draw against parameter count.

Reads the model dataset from Dom's ENGF0003 coursework (Epoch AI's AI-model data: one row per
model, with Parameters and TrainingPowerDraw_W_ columns), keeps the models that have both, as
the coursework's MATLAB does, and writes js/data/scaling.js with each model's name, parameter
count and power draw. Prints the log10-log10 least-squares fit, which the page recomputes.

Usage: python3 tools/scaling_data.py path/to/dataset2.csv
"""
import csv
import json
import math
import pathlib
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "js" / "data" / "scaling.js"


def num(s):
    try:
        x = float(s)
    except (TypeError, ValueError):
        return None
    return x if math.isfinite(x) and x > 0 else None


def main(src):
    rows = list(csv.DictReader(open(src, encoding="utf-8")))
    pts = []
    for r in rows:
        n, p = num(r.get("Parameters")), num(r.get("TrainingPowerDraw_W_"))
        if n and p:
            pts.append([" ".join((r.get("Model") or "").split()), float("%.4g" % n), float("%.4g" % p)])
    pts.sort(key=lambda q: q[1])
    xs = [math.log10(q[1]) for q in pts]
    ys = [math.log10(q[2]) for q in pts]
    k = len(pts)
    mx, my = sum(xs) / k, sum(ys) / k
    sxy = sum((a - mx) * (b - my) for a, b in zip(xs, ys))
    sxx = sum((a - mx) ** 2 for a in xs)
    syy = sum((b - my) ** 2 for b in ys)
    slope = sxy / sxx
    print("%d models of %d; log10 P = %.3f log10 N %+.3f, R^2 %.3f" % (k, len(rows), slope, my - slope * mx, sxy * sxy / (sxx * syy)))
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "// generated by tools/scaling_data.py from Dom's ENGF0003 coursework dataset (Epoch AI's\n"
        "// AI-model data): [model, parameters, training power draw in W], by parameter count\n"
        "export default %s;\n" % json.dumps(pts, separators=(",", ":"), ensure_ascii=False), encoding="utf-8")
    print("wrote %s (%.1f KB)" % (OUT.relative_to(OUT.parent.parent.parent), OUT.stat().st_size / 1024))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
