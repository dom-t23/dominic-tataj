"""Split the drone-racing demo's flights.js into one file per flight.

The demo generator (`python -m vdr.demo` in vision-drone-racing) writes every recorded
flight into a single flights.js (about 7 MB). The site only shows one flight at a time,
so this writes flights/index.js with the metadata for all flights (no frames) and
flights/<seed>-<method>.js with each flight's frames, fetched when it is picked.

index.js also carries a poster for the player before LOAD: the first flight's path and one
mid-flight camera frame, the one in the middle third with the largest gate outline that
still leaves most of the view clear.

Usage: python3 tools/split_flights.py path/to/flights.js

tools/export_flights.py records the flights itself (with the pipeline strip's extra fields)
and writes them through write() here.
"""
import json
import pathlib
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "flights"


def main(src):
    text = pathlib.Path(src).read_text(encoding="utf-8")
    write(json.loads(text[text.index("["):].rstrip().rstrip(";")), "tools/split_flights.py")


def write(flights, source):
    """Replace flights/ with one file per flight, and index.js. `source` names the generator."""
    OUT.mkdir(exist_ok=True)
    for old in OUT.glob("*.js"):
        old.unlink()

    index = []
    for f in flights:
        fid = "%s-%s" % (f["seed"], f["method"])
        data = json.dumps(f, separators=(",", ":"))
        (OUT / (fid + ".js")).write_text(
            "window.FLIGHT_DATA = window.FLIGHT_DATA || {};\n"
            "window.FLIGHT_DATA[%s] = %s;\n" % (json.dumps(fid), data), encoding="utf-8")
        meta = {k: v for k, v in f.items() if k != "frames"}
        meta["id"] = fid
        index.append(meta)
        print("%-20s %5.2f MB" % (fid + ".js", len(data) / 1e6))

    poster = make_poster(flights[0], index[0]["id"])
    (OUT / "index.js").write_text(
        "// generated by %s -- one entry per file in this folder\n"
        "window.FLIGHT_INDEX = %s;\n"
        "window.FLIGHT_POSTER = %s;\n" % (source, json.dumps(index, separators=(",", ":")),
                                         json.dumps(poster, separators=(",", ":"))),
        encoding="utf-8")
    print("poster: %s frame %d" % (poster["id"], poster["idx"]))


def quad_area(c):
    xs, ys = c[0::2], c[1::2]
    return abs(sum(xs[i] * ys[(i + 1) % 4] - xs[(i + 1) % 4] * ys[i] for i in range(4))) / 2


def make_poster(f, fid):
    frames = f["frames"]
    w, h = f["image_size"]
    n = len(frames)
    best, at = -1, n // 2
    for i in range(int(0.35 * n), int(0.65 * n) + 1):
        outer = [quad_area(q["c"]) / (w * h) for q in frames[i]["q"] if q["k"] == "o"]
        a = max(outer, default=-1)
        if best < a <= 0.3:
            best, at = a, i
    # The whole path keeps the map's scale identical to the full replay; one frame in full.
    path = [{k: fr[k] for k in ("t", "p", "e", "g")} for fr in frames]
    path[at] = frames[at]
    return {"id": fid, "idx": at, "frames": path}


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
